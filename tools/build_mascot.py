#!/usr/bin/env python3
"""Emit mascot/atlas.classic.js, the classic-script copy of mascot/atlas.js that index.html loads before os.js (os.js is not a module).
It is the same code with the `export` keywords dropped, wrapped in a function that sets window.MASCOT. Run it after editing mascot/atlas.js,
before tools/bump_assets.py:

    python3 tools/build_mascot.py && python3 tools/bump_assets.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'mascot', 'atlas.js')
import glob
DATA = ['lean', 'feet', 'hands', 'faces', 'body']
PARTS = [os.path.join(ROOT, 'mascot', n + '.js') for n in DATA] + sorted(glob.glob(os.path.join(ROOT, 'mascot', 'anim_*.js'))) + [SRC]   # atlas.js imports all the data files, so they come first
OUT = os.path.join(ROOT, 'mascot', 'atlas.classic.js')

def build():
    src = ''
    for part in PARTS:
        with open(part, encoding='utf-8') as f:
            src += re.sub(r"^import .* from '\./[\w]+\.js';\n", '', f.read(), flags=re.M).rstrip('\n') + '\n'
    return src

src = build()
names = re.findall(r'^export (?:const|function) ([A-Za-z_$][\w$]*)', src, flags=re.M)
body = re.sub(r'^export ', '', src, flags=re.M)
out = ('/* GENERATED by tools/build_mascot.py from mascot/body.js and mascot/atlas.js. Do not edit. */\n'
       '(()=>{\n' + body.rstrip('\n') + '\nwindow.MASCOT={' + ','.join(names) + '};\n})();\n')

if '--print' in sys.argv:        # the test compares this with the file on disk
    sys.stdout.write(out)
    sys.exit(0)
with open(OUT, 'w', encoding='utf-8') as f:
    f.write(out)
print(f'wrote {os.path.relpath(OUT, ROOT)} ({len(names)} exports: {", ".join(names)})')
